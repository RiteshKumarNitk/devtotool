/// Builds a Markdown bug report. Pure, so it can be unit tested.
String buildBugReportMarkdown({
  required String description,
  required CurrentPage page,
  required List<ConsoleLog> logs,
  required List<NetworkRequest> requests,
  required Map<String, dynamic> deviceInfo,
  Map<String, dynamic>? vitals,
  DateTime? now,
  int maxItems = 30,
}) {
  final b = StringBuffer();
  final time = (now ?? DateTime.now()).toIso8601String();
  b.writeln('# Bug report');
  b.writeln();
  b.writeln('- **URL:** ${page.url.isEmpty ? '(unknown)' : page.url}');
  if (page.title.isNotEmpty) b.writeln('- **Page title:** ${page.title}');
  b.writeln('- **Reported at:** $time');
  final device = deviceInfo['device'];
  if (device is Map) {
    b.writeln('- **User agent:** ${device['userAgent'] ?? '?'}');
    b.writeln('- **Screen:** ${device['screenWidth']}×${device['screenHeight']} @${device['pixelRatio']}x');
    b.writeln('- **Language / timezone:** ${device['language']} / ${device['timezone']}');
  }
  b.writeln();
  b.writeln('## Description');
  b.writeln();
  b.writeln(description.trim().isEmpty ? '_No description provided._' : description.trim());
  b.writeln();

  final errors = logs.where((l) => l.level == 'error' || l.level == 'warn').toList();
  b.writeln('## Console errors & warnings (${errors.length})');
  b.writeln();
  if (errors.isEmpty) {
    b.writeln('None.');
  } else {
    b.writeln('```');
    for (final l in errors.reversed.take(maxItems).toList().reversed) {
      b.writeln('[${l.timestamp.toIso8601String()}] ${l.level.toUpperCase()}: ${l.message}');
    }
    b.writeln('```');
    if (errors.length > maxItems) b.writeln('_…${errors.length - maxItems} earlier entries omitted._');
  }
  b.writeln();

  final failed = requests.where((r) => r.failed || r.status >= 400).toList();
  b.writeln('## Failed requests (${failed.length})');
  b.writeln();
  if (failed.isEmpty) {
    b.writeln('None.');
  } else {
    for (final r in failed.reversed.take(maxItems)) {
      b.writeln('### ${r.method} ${r.url}');
      b.writeln();
      b.writeln('- Status: ${r.failed ? 'failed' : r.status}${r.error != null ? ' (${r.error})' : ''}');
      b.writeln('- Duration: ${r.duration} ms');
      b.writeln();
      b.writeln('```bash');
      b.writeln(toCurl(r));
      b.writeln('```');
      final body = r.responseBody;
      if (body != null && body.isNotEmpty) {
        b.writeln();
        b.writeln('Response (first 500 chars):');
        b.writeln('```');
        b.writeln(body.length > 500 ? '${body.substring(0, 500)}…' : body);
        b.writeln('```');
      }
      b.writeln();
    }
  }

  final v = vitals?['vitals'];
  if (v is Map) {
    b.writeln('## Web Vitals');
    b.writeln();
    b.writeln('| LCP | CLS | INP | FCP | TTFB |');
    b.writeln('|---|---|---|---|---|');
    String ms(Object? x) => x == null ? '–' : '$x ms';
    b.writeln('| ${ms(v['lcp'])} | ${v['cls'] ?? '–'} | ${ms(v['inp'])} | ${ms(v['fcp'])} | ${ms(v['ttfb'])} |');
    b.writeln();
  }
  b.writeln('---');
  b.writeln('_Generated by Debug Browser (InnovateX Technology). Full network log attached as HAR._');
  return b.toString();
}

class BugReportService {
  /// Captures a screenshot and shares report.md + screenshot.png + network.har.
  static Future<bool> shareReport(WidgetRef ref, String description) async {
    try {
      final dir = await getTemporaryDirectory();
      final stamp = DateTime.now().millisecondsSinceEpoch;
      final files = <XFile>[];

      final markdown = buildBugReportMarkdown(
        description: description,
        page: ref.read(currentPageProvider),
        logs: ref.read(consoleLogsProvider),
        requests: ref.read(networkRequestsProvider),
        deviceInfo: ref.read(devicePerformanceProvider),
        vitals: ref.read(pageDataProvider)['vitals'],
      );
      final md = File('${dir.path}/bug_report_$stamp.md');
      await md.writeAsString(markdown);
      files.add(XFile(md.path, mimeType: 'text/markdown'));

      try {
        final png = await ref.read(screenshotControllerProvider).capture();
        if (png != null) {
          final f = File('${dir.path}/bug_screenshot_$stamp.png');
          await f.writeAsBytes(png);
          files.add(XFile(f.path, mimeType: 'image/png'));
        }
      } catch (e) {
        debugPrint('Bug report screenshot skipped: $e');
      }

      final requests = ref.read(networkRequestsProvider);
      if (requests.isNotEmpty) {
        final har = File('${dir.path}/bug_network_$stamp.har');
        await har.writeAsString(jsonEncode(buildHar(requests)));
        files.add(XFile(har.path, mimeType: 'application/json'));
      }

      await SharePlus.instance.share(ShareParams(
        files: files,
        subject: 'Bug report: ${ref.read(currentPageProvider).url}',
        text: markdown.length > 3000 ? '${markdown.substring(0, 3000)}…' : markdown,
      ));
      return true;
    } catch (e, st) {
      debugPrint('Bug report failed: $e\n$st');
      return false;
    }
  }
}
